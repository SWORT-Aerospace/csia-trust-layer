"""Plant families Q0, Q1 and Q2, implemented independently of the estimator.

WHY NOT REUSE ``csia_active_evidence.battery_1rc``
---------------------------------------------------
Because the prior campaign's certificate margin turned out to be bit-identical
across all three of its plants (see ``COUNTEREXAMPLE_LOG.md`` IV-4). Plant
truth generated by code that shares structure with the thing being tested can
hide that. These plants share no code with the prior simulator and, more
importantly, use a **different numerical path**:

* the prior plant integrates the polarization state and the command lag with
  explicit forward Euler, ``x += dt * f(x)``;
* these plants use the **exact zero-order-hold solution** of the same linear
  ODE, ``x <- x*exp(-dt/tau) + x_inf*(1 - exp(-dt/tau))``, which is exact for
  a current held constant across the step, and **RK4** for the nonlinear
  thermal state.

At 50 Hz with a 0.25 s lag the two disagree by about 4% on the per-step
coefficient (``dt/tau = 0.0800`` against ``1 - exp(-dt/tau) = 0.0769``). That
disagreement is deliberate. A certificate that only works against the
integrator it was developed on is not a certificate, and this is how we find
out. ``tests/test_iv_plants.py`` pins the exact solution against closed form,
which forward Euler fails at this step size.

WHAT IS AND IS NOT CLAIMED
--------------------------
Every parameter here is **synthetic**. There is no cell data in this
repository and none is reachable from this host. ``SYNTHETIC_Q`` is a
self-consistent set of numbers in SI units and it is not a measurement of any
chemistry. Nothing derived from it characterises any real battery, and no
result here implies hardware representativeness.

LAYER
-----
This module is Layer B. It produces ground truth and must never be imported
by Layer A.
"""
from __future__ import annotations

import math
from dataclasses import asdict, dataclass, field, replace
from typing import Callable, Dict, Optional, Tuple

import numpy as np

from .truth import GroundTruth

LAYER = "B"
TRUTH_BEARING = True
SCHEMA = "csia.independent_validation.plants/1"

#: The seven independent streams. A branch that does not fire must not
#: advance a stream belonging to a different subsystem; separate generators
#: make that structural instead of a convention we hope holds.
STREAM_NAMES = ("plant", "voltage_sensor", "current_sensor", "controller",
                "environment", "telemetry", "unknown_fault")

#: SYNTHETIC. NOT A MEASUREMENT OF ANY CHEMISTRY.
SYNTHETIC_Q = dict(
    ocv_full=16.8,          # V at z = 1
    ocv_empty=14.0,         # V at z = 0
    ocv_curvature=0.45,     # V, sag away from the straight line
    ocv_curvature_q2=1.10,  # V, Q2's stronger, asymmetric characteristic
    r0=0.040,               # ohm
    r1=0.015,               # ohm, first polarization branch
    tau1_s=13.5,            # s
    r2=0.006,               # ohm, second branch, Q2 only
    tau2_s=1.20,            # s
    hysteresis_v=0.035,     # V, Q2 only
    hysteresis_gamma=60.0,  # dimensionless throughput rate, Q2 only;
                            # the value already declared by the prior
                            # phase's multi-RC pack. At 20 A and 4 Ah
                            # it gives a hysteresis time constant of
                            # about 12 s, i.e. comparable to a probe
                            # window. A first draft used 0.08, which
                            # works out at roughly 9000 s: the state
                            # would have been frozen across every
                            # probe and Q2 would have carried a
                            # constant offset dressed up as a dynamic
                            # effect.
    capacity_ah=4.0,
    t_ambient_c=22.0,
    thermal_rise_per_amp2=0.004,   # K per A^2
    thermal_tau_s=45.0,            # s, how fast it relaxes back to ambient
    r0_temp_coeff=-3.0e-4,         # ohm per K
    z_initial=0.85,
)

#: The measurement chain. Also synthetic.
SYNTHETIC_SENSING = dict(
    sigma_v=0.020, sigma_i=0.080,
    bias_v=0.0, bias_i=0.0,
    scale_v=0.0, scale_i=0.0,
    quantum_v=0.0, quantum_i=0.0,
    delay_v_s=0.0, delay_i_s=0.0,
    dropout=0.0,
    timestamp_jitter_s=0.0,
    sample_phase=0.0,
    antialias_tau_s=0.0,
)

#: The closed loop. ``lag_s`` is why a palindromic command is not a
#: palindromic current, which is the whole subject of this line of work.
SYNTHETIC_LOOP = dict(lag_s=0.25, hz=50.0, base_current=20.0,
                      saturation_a=60.0, controller_sigma=0.01,
                      process_sigma=0.01)

PLANTS = ("Q0", "Q1", "Q2")


@dataclass(frozen=True)
class QParams:
    ocv_full: float
    ocv_empty: float
    ocv_curvature: float
    ocv_curvature_q2: float
    r0: float
    r1: float
    tau1_s: float
    r2: float
    tau2_s: float
    hysteresis_v: float
    hysteresis_gamma: float
    capacity_ah: float
    t_ambient_c: float
    thermal_rise_per_amp2: float
    thermal_tau_s: float
    r0_temp_coeff: float
    z_initial: float

    def ocv(self, z: float, plant: str) -> float:
        """Open-circuit voltage. Q2's characteristic is deliberately harsher.

        NOT a fitted cell curve. A monotone base with a curvature term, and
        for Q2 an additional asymmetric term that the estimator has no
        parameter for.
        """
        z = min(max(z, 0.0), 1.0)
        linear = self.ocv_empty + (self.ocv_full - self.ocv_empty) * z
        curve = self.ocv_curvature * z * (1.0 - z) * 4.0
        if plant != "Q2":
            return linear - curve
        extra = self.ocv_curvature_q2 * (z ** 3 - z) * 0.5
        return linear - curve + extra

    def r0_at(self, t_c: float) -> float:
        return self.r0 + self.r0_temp_coeff * (t_c - self.t_ambient_c)

    def to_dict(self) -> Dict:
        return asdict(self)


@dataclass(frozen=True)
class Sensing:
    sigma_v: float
    sigma_i: float
    bias_v: float
    bias_i: float
    scale_v: float
    scale_i: float
    quantum_v: float
    quantum_i: float
    delay_v_s: float
    delay_i_s: float
    dropout: float
    timestamp_jitter_s: float
    sample_phase: float
    antialias_tau_s: float

    def to_dict(self) -> Dict:
        return asdict(self)


@dataclass(frozen=True)
class Loop:
    lag_s: float
    hz: float
    base_current: float
    saturation_a: float
    controller_sigma: float
    process_sigma: float

    def to_dict(self) -> Dict:
        return asdict(self)


@dataclass(frozen=True)
class Observation:
    """Everything Layer A is allowed to see. Nothing else may be added here.

    ``tests/test_iv_layers.py`` pins these field names. Adding a field that
    encodes truth -- a fault label, a true resistance, a hidden state -- is
    the leak this schema exists to prevent, and the test fails on any field
    name it does not recognise.
    """

    t: np.ndarray               # s, the timestamps as reported, jitter included
    i_meas: np.ndarray          # A, measured pack current
    v_meas: np.ndarray          # V, measured terminal voltage
    i_command: np.ndarray       # A, what was asked for
    valid: np.ndarray           # bool, False where telemetry dropped out
    saturated: np.ndarray       # bool, where the loop hit its current limit
    dt_nominal: float           # s, the scheduled sample interval

    @property
    def n(self) -> int:
        return int(self.t.size)

    def kept(self) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
        """The samples an estimator may actually use."""
        return self.t[self.valid], self.i_meas[self.valid], \
            self.v_meas[self.valid]


def streams(seed: int) -> Dict[str, np.random.Generator]:
    """One generator per physical subsystem, spawned from one seed."""
    sequence = np.random.SeedSequence(seed)
    children = sequence.spawn(len(STREAM_NAMES))
    return {name: np.random.default_rng(child)
            for name, child in zip(STREAM_NAMES, children)}


def _zoh(state: float, target: float, dt: float, tau: float) -> float:
    """Exact step of ``dx/dt = (target - x)/tau`` for constant ``target``.

    This is the line that makes these plants numerically independent of the
    prior simulator, which used ``state + dt/tau * (target - state)``.
    """
    if tau <= 0.0:
        return target
    decay = math.exp(-dt / tau)
    return state * decay + target * (1.0 - decay)


def _rk4_thermal(temp: float, current: float, dt: float,
                 params: QParams) -> float:
    """RK4 on ``dT/dt = (rise*I^2 - (T - T_amb))/tau``.

    The thermal state is the one genuinely nonlinear-in-input state, so it
    gets the higher-order integrator. Using a different method here than the
    linear states is also a small guard against a shared-integrator artifact.
    """
    tau = max(params.thermal_tau_s, 1e-9)

    def f(value: float) -> float:
        drive = params.thermal_rise_per_amp2 * current * current
        return (drive - (value - params.t_ambient_c)) / tau

    k1 = f(temp)
    k2 = f(temp + 0.5 * dt * k1)
    k3 = f(temp + 0.5 * dt * k2)
    k4 = f(temp + dt * k3)
    return temp + (dt / 6.0) * (k1 + 2.0 * k2 + 2.0 * k3 + k4)


def _quantize(value: np.ndarray, step: float) -> np.ndarray:
    if step <= 0.0:
        return value
    return np.round(value / step) * step


def _delay(values: np.ndarray, samples: int) -> np.ndarray:
    if samples <= 0:
        return values
    out = np.empty_like(values)
    out[:samples] = values[0]
    out[samples:] = values[:-samples]
    return out


def _antialias(values: np.ndarray, dt: float, tau: float) -> np.ndarray:
    """A causal one-pole filter standing in for an anti-alias stage."""
    if tau <= 0.0:
        return values
    out = np.empty_like(values)
    state = float(values[0])
    for k, value in enumerate(values):
        state = _zoh(state, float(value), dt, tau)
        out[k] = state
    return out


def simulate(command: Callable[[float], float], *, plant: str, duration: float,
             seed: int, params: Optional[QParams] = None,
             sensing: Optional[Sensing] = None, loop: Optional[Loop] = None,
             r0_delta: float = 0.0, drift_v_per_s: float = 0.0,
             ringing_amplitude_v: float = 0.0, ringing_hz: float = 6.0,
             ringing_damping: float = 0.4, ringing_phase_rad: float = 0.0,
             ringing_onset_s: float = 0.0,
             lag_s: Optional[float] = None,
             observer: Optional[Callable[[float, float, float], None]] = None,
             ) -> Tuple[Observation, GroundTruth]:
    """Run one trial and return what is observable and what was true.

    ``command(t)`` returns the **excess** current demand in amps, on top of
    ``loop.base_current``. ``observer(t_k, i_k, v_k)`` is called after sample
    ``k`` is measured and before sample ``k+1`` is commanded, so a feedback
    probe can react to realized current without ever seeing the future.

    The return is a pair and the two halves go to different layers. Handing
    the :class:`~.truth.GroundTruth` to anything on the deployable side is the
    leak the architectural tests exist to catch.
    """
    if plant not in PLANTS:
        raise ValueError(f"unknown plant {plant!r}; have {PLANTS}")
    params = params or QParams(**SYNTHETIC_Q)
    sensing = sensing or Sensing(**SYNTHETIC_SENSING)
    loop = loop or Loop(**SYNTHETIC_LOOP)
    rng = streams(seed)

    dt = 1.0 / loop.hz
    n = max(int(round(duration * loop.hz)), 8)
    true_lag = loop.lag_s if lag_s is None else lag_s

    # Every stream is drawn as one block, before the loop, from its own
    # generator. That is what makes an inactive branch harmless: not firing
    # the ringing term cannot shift the current-sensor sequence, because they
    # never share a generator. tests/test_iv_plants.py asserts exactly this.
    i_noise = rng["current_sensor"].normal(0.0, sensing.sigma_i, n)
    v_noise = rng["voltage_sensor"].normal(0.0, sensing.sigma_v, n)
    controller_noise = rng["controller"].normal(0.0, loop.controller_sigma, n)
    process_noise = rng["plant"].normal(0.0, loop.process_sigma, n)
    # Drawn unconditionally and scaled afterwards. Drawing it only when
    # jitter is enabled would shift the telemetry stream and silently change
    # the dropout mask -- an inactive branch perturbing an active one, which
    # is precisely the defect this design is supposed to make impossible.
    jitter = (rng["telemetry"].standard_normal(n)
              * max(sensing.timestamp_jitter_s, 0.0))
    keep = rng["telemetry"].random(n) >= sensing.dropout
    keep[0] = True
    # Drawn whether or not the fault fires, so that the *decision* to inject
    # cannot change any other stream. Unused draws are simply discarded.
    ringing_phase_noise = rng["unknown_fault"].normal(0.0, 1.0, n)

    r0_nominal = params.r0
    r0_realized = params.r0 + r0_delta

    has_r1 = plant in ("Q1", "Q2")
    has_r2 = plant == "Q2"
    has_hysteresis = plant == "Q2"

    z = params.z_initial
    v1 = 0.0
    v2 = 0.0
    hysteresis = 0.0
    temp = params.t_ambient_c
    i_real = loop.base_current

    t = np.arange(n, dtype=float) * dt + sensing.sample_phase * dt
    i_true = np.empty(n)
    v_true = np.empty(n)
    v1_true = np.empty(n)
    i_command = np.empty(n)
    saturated = np.zeros(n, dtype=bool)
    i_raw = np.empty(n)
    v_raw = np.empty(n)

    capacity_as = params.capacity_ah * 3600.0

    for k in range(n):
        demand = loop.base_current + float(command(t[k]))
        demand += controller_noise[k]
        i_command[k] = demand

        # Exact ZOH on the command-to-current lag, NOT forward Euler.
        i_real = _zoh(i_real, demand, dt, true_lag)
        if abs(i_real) > loop.saturation_a:
            i_real = math.copysign(loop.saturation_a, i_real)
            saturated[k] = True
        i_real += process_noise[k]
        i_true[k] = i_real

        # Linear states, exact for a current held across the step.
        if has_r1:
            v1 = _zoh(v1, i_real * params.r1, dt, params.tau1_s)
        if has_r2:
            v2 = _zoh(v2, i_real * params.r2, dt, params.tau2_s)
        if has_hysteresis:
            # Plett-style: the state relaxes towards sign(I) at a rate set by
            # throughput, so it correlates with the regressor and cannot be
            # seen in the residual. That is what made RC-11 a false
            # certification in the prior phase.
            rate = params.hysteresis_gamma * abs(i_real) / capacity_as
            hysteresis = _zoh(hysteresis, math.copysign(1.0, i_real) if
                              i_real != 0.0 else 0.0, dt, 1.0 / max(rate,
                                                                    1e-9))
        v1_true[k] = v1

        temp = _rk4_thermal(temp, i_real, dt, params)
        z -= i_real * dt / capacity_as

        r0_effective = r0_realized + params.r0_temp_coeff * (
            temp - params.t_ambient_c)
        terminal = params.ocv(z, plant) - r0_effective * i_real
        if has_r1:
            terminal -= v1
        if has_r2:
            terminal -= v2
        if has_hysteresis:
            terminal += params.hysteresis_v * hysteresis
        terminal += drift_v_per_s * t[k]

        if ringing_amplitude_v > 0.0 and t[k] >= ringing_onset_s:
            elapsed = t[k] - ringing_onset_s
            terminal += (ringing_amplitude_v
                         * math.exp(-ringing_damping * elapsed)
                         * math.sin(2.0 * math.pi * ringing_hz * elapsed
                                    + ringing_phase_rad))
        v_true[k] = terminal

        i_raw[k] = (1.0 + sensing.scale_i) * i_real + sensing.bias_i
        v_raw[k] = (1.0 + sensing.scale_v) * terminal + sensing.bias_v

        if observer is not None:
            observer(float(t[k]), float(i_raw[k] + i_noise[k]),
                     float(v_raw[k] + v_noise[k]))

    i_meas = _antialias(i_raw, dt, sensing.antialias_tau_s) + i_noise
    v_meas = _antialias(v_raw, dt, sensing.antialias_tau_s) + v_noise
    i_meas = _delay(i_meas, int(round(sensing.delay_i_s * loop.hz)))
    v_meas = _delay(v_meas, int(round(sensing.delay_v_s * loop.hz)))
    i_meas = _quantize(i_meas, sensing.quantum_i)
    v_meas = _quantize(v_meas, sensing.quantum_v)

    observation = Observation(
        t=t + jitter, i_meas=i_meas, v_meas=v_meas, i_command=i_command,
        valid=keep, saturated=saturated, dt_nominal=dt)

    label = "none"
    if ringing_amplitude_v > 0.0:
        label = "unknown_ringing"
    elif r0_delta != 0.0:
        label = "r0_increase" if r0_delta > 0 else "r0_decrease"

    truth = GroundTruth(
        plant=plant, r0_nominal=r0_nominal, r0_realized=r0_realized,
        fault_label=label,
        r1=params.r1 if has_r1 else 0.0,
        tau1_s=params.tau1_s if has_r1 else 0.0,
        r2=params.r2 if has_r2 else 0.0,
        tau2_s=params.tau2_s if has_r2 else 0.0,
        hysteresis_v=params.hysteresis_v if has_hysteresis else 0.0,
        hysteresis_gamma=params.hysteresis_gamma if has_hysteresis else 0.0,
        ocv_curvature=params.ocv_curvature,
        ringing_amplitude_v=ringing_amplitude_v,
        ringing_hz=ringing_hz if ringing_amplitude_v > 0 else 0.0,
        ringing_damping=ringing_damping if ringing_amplitude_v > 0 else 0.0,
        ringing_phase_rad=ringing_phase_rad if ringing_amplitude_v > 0 else 0.0,
        ringing_onset_s=ringing_onset_s if ringing_amplitude_v > 0 else 0.0,
        drift_v_per_s=drift_v_per_s, lag_s=true_lag,
        i_true=tuple(float(x) for x in i_true),
        v_true=tuple(float(x) for x in v_true),
        v1_true=tuple(float(x) for x in v1_true),
        seed=seed)
    del ringing_phase_noise  # drawn for stream alignment, deliberately unused
    return observation, truth
